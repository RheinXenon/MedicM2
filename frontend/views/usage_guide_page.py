"""
使用说明页面
"""
import streamlit as st


def render_usage_guide_page():
    """渲染使用说明页面"""
    st.markdown("""
## 使用指南

### 1️⃣ 初始化系统
点击侧边栏的"初始化系统"按钮，系统将：
- 加载5个科室的医生Agent
- 加载CMeIEV2数据集（715种疾病）
- 初始化病例库和经验库

### 2️⃣ 开始治疗
1. 输入病人数量（1-1000）✨ **支持大批量测试**
2. 选择科室筛选（可选）
3. 点击"开始治疗"
4. 观察实时治疗日志和统计信息

### 3️⃣ 观察进化
- **统计** - 查看历史以来所有病人的统计数据 ✨ **新功能：历史记录**
  - 历史总体统计：所有治疗过的病人数据
  - 当前系统统计：本次session的数据
  - 医生表现和治疗时间线
- **病例库** - 查看积累的成功案例 ✨ **新功能：查看详细病例**
  - 按科室筛选病例
  - 查看每个病例的详细信息
- **经验库** - 查看从失败中学到的规则 ✨ **新功能：查看详细规则**
  - 按科室筛选规则
  - 查看规则内容、触发条件、应用效果

### 4️⃣ 验证学习效果
多次运行治疗，观察：
- 诊断准确率逐渐提升
- 病例库和经验库持续增长
- 治疗成功率改善
- **历史统计数据持续累积** ✨

### 5️⃣ 保存和管理
- 点击"保存"按钮保存当前状态
  - 保存医院治疗记录
  - 保存历史统计数据 ✨
- 点击"清空"按钮清空知识库
- 保存的文件位于 `./simulation_results` 目录

### 💡 提示
- 病例库和经验库会持久化保存
- 历史统计数据在保存后可持久化 ✨
- 重启系统后继续使用已有知识
- 可以清空知识库重新训练
- 支持大批量病人治疗（最多1000人）✨

### ⚙️ 技术栈
- **前端框架：** Streamlit
- **AI引擎：** OpenAI API
- **知识库：** ChromaDB
- **数据集：** CMeIEV2 医学数据集
""")
